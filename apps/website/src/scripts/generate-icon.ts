import fs from "fs"
import path from "path"
import { ICON_SLOT_REPLACEMENTS } from "@/registry/icon/icon-slot"

const jsonOutputPath = "public/r/icon/icon.json"

// Ensure public directory exists
const dir = path.dirname(jsonOutputPath)
if (!fs.existsSync(dir)) {
	fs.mkdirSync(dir, { recursive: true })
	console.log("📁 Created directory:", dir)
}

// 1. Write icon.json
fs.writeFileSync(
	jsonOutputPath,
	JSON.stringify(ICON_SLOT_REPLACEMENTS, null, 2)
)
console.log("Saved IconJSON at:", jsonOutputPath)

// 2. Generate per-library static icon map files
const mapsDir = path.join(process.cwd(), "src/registry/icon/maps")
if (!fs.existsSync(mapsDir)) {
	fs.mkdirSync(mapsDir, { recursive: true })
}

// Deduplicate slots in case of duplicates in ICON_SLOT_REPLACEMENTS
const slotsMap = new Map<string, (typeof ICON_SLOT_REPLACEMENTS)[number]>()
for (const item of ICON_SLOT_REPLACEMENTS) {
	slotsMap.set(item.slot, item)
}
const uniqueSlots = Array.from(slotsMap.values())

// --- Lucide map ---
const uniqueLucide = Array.from(
	new Set(uniqueSlots.map((i) => i.lucideIcon))
).sort()

const lucideContent = `// This file is auto-generated by src/scripts/generate-icon.ts
// Do not edit manually.

import type { LucideIcon } from "lucide-react"
import type { IconSlot } from "@/registry/icon/icon-libraries"

import {
${uniqueLucide.map((name) => `\t${name},`).join("\n")}
} from "lucide-react"

export const LUCIDE_ICON_MAP: Record<IconSlot, LucideIcon> = {
${uniqueSlots.map((i) => `\t${JSON.stringify(i.slot)}: ${i.lucideIcon},`).join("\n")}
}
`

const lucideOutputPath = path.join(mapsDir, "lucide.ts")
fs.writeFileSync(lucideOutputPath, lucideContent, "utf8")
console.log("Saved Lucide icon map at:", lucideOutputPath)

// --- Hugeicons map ---
const uniqueHugeicons = Array.from(
	new Set(uniqueSlots.map((i) => i.hugeiconsIcon))
).sort()

const hugeiconsContent = `// This file is auto-generated by src/scripts/generate-icon.ts
// Do not edit manually.

import type { IconSvgElement } from "@hugeicons/react"
import type { IconSlot } from "@/registry/icon/icon-libraries"

import {
${uniqueHugeicons.map((name) => `\t${name},`).join("\n")}
} from "@hugeicons/core-free-icons"

export const HUGEICONS_ICON_MAP: Record<IconSlot, IconSvgElement> = {
${uniqueSlots.map((i) => `\t${JSON.stringify(i.slot)}: ${i.hugeiconsIcon},`).join("\n")}
}
`

const hugeiconsOutputPath = path.join(mapsDir, "hugeicons.ts")
fs.writeFileSync(hugeiconsOutputPath, hugeiconsContent, "utf8")
console.log("Saved Hugeicons icon map at:", hugeiconsOutputPath)
