const AvatarTile = ({ src, index }: { src: string; index: number }) => {
	const [copied, setCopied] = useState(false)
	const [open, setOpen] = useState<boolean>(false)

	const handleCopy = async (e: React.MouseEvent) => {
		e.stopPropagation()
		try {
			const res = await fetch(src)
			const blob = await res.blob()
			await navigator.clipboard.write([
				new ClipboardItem({ [blob.type]: blob }),
			])
			setCopied(true)
			setTimeout(() => setCopied(false), 1500)
		} catch {
			await navigator.clipboard.writeText(src)
		}
	}

	return (
		<div className="border-border bg-bg-secondary group relative aspect-square w-full overflow-hidden rounded-xl border">
			<Image
				src={src}
				alt={`Generated avatar ${index + 1}`}
				fill
				sizes="(max-width: 640px) 25vw, (max-width: 768px) 20vw, 14vw"
				className="object-cover"
			/>

			<div
				className={cn(
					"absolute right-2 top-2 transition-opacity",
					open ? "opacity-100" : "opacity-0 group-hover:opacity-100"
				)}>
				<Dropdown open={open} onOpenChange={setOpen}>
					<DropdownTrigger asChild>
						<CompactButton
							aria-label="Button with Down Arrow"
							size="20"
							variant="ghost"
							color="neutral"
							onClick={(e) => e.stopPropagation()}>
							<MoreHorizontal className="size-4" />
						</CompactButton>
					</DropdownTrigger>

					<DropdownContent align="end" className="w-40">
						<DropdownItem onClick={handleCopy}>
							<Copy />
							Copy
						</DropdownItem>
						<DropdownItem>
							<Download />
							Download
						</DropdownItem>
						<DropdownItem className="text-danger">
							<Trash2 />
							Delete
						</DropdownItem>
					</DropdownContent>
				</Dropdown>
			</div>

			<div className="absolute bottom-2 right-2 opacity-0 transition-opacity group-hover:opacity-100">
				<Button color="neutral" variant="outline" onClick={handleCopy}>
					{copied ? "Copied" : "Copy"}
				</Button>
			</div>
		</div>
	)
}
